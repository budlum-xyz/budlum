//! The post-quantum measurement tables.
//!
//! The numbers come from the node library, not from a copy: `examples/pq_measure.rs`
//! links `budlum_core` and prints Markdown, and this tool runs it and splices the result into
//! `docs/pq/MEASUREMENTS.md` between two markers, the same `--write` / `--check` pattern as
//! `stark-soundness`.
//!
//! Two outputs, and only one of them is compared:
//!
//! - `tables` (scheme and suite sizes read from the registry, signature material per
//!   transaction, QC blob bounds for 50 to 1000 validators, daily anchor and seal traffic) is
//!   deterministic. `--check` fails when the document differs from it.
//! - `--timings` (sign and verify of ML-DSA-65 and 87, SLH-DSA-SHAKE-256s, Ed25519, the
//!   composite and the dual-library verifier) depends on the machine. It is printed, uploaded as
//!   a CI artifact, and never compared.

use crate::report::Report;
use std::path::Path;
use std::process::Command;

const BEGIN: &str = "<!-- pq-measure:begin -->";
const END: &str = "<!-- pq-measure:end -->";
const DOC_REL: &str = "docs/pq/MEASUREMENTS.md";
const INTRO: &str = "## Sizes and traffic\n\nGenerated by `cargo run --manifest-path xtask/tools/Cargo.toml -- pq-measure --write`. `--check` fails when this section no longer matches the node library. The source is `examples/pq_measure.rs`. Timings are machine dependent, are produced by `pq-measure --timings` and are uploaded as a CI artifact instead of being written here.\n\n";

fn wrap(section: &str) -> String {
    format!("{BEGIN}\n{INTRO}{section}{END}\n")
}

/// Insert or replace the generated block in `existing`.
#[must_use]
pub fn splice(existing: &str, section: &str) -> String {
    let block = wrap(section);
    if let (Some(b), Some(e)) = (existing.find(BEGIN), existing.find(END)) {
        if b < e {
            let after = e + END.len();
            let after = if existing[after..].starts_with('\n') {
                after + 1
            } else {
                after
            };
            return format!("{}{}{}", &existing[..b], block, &existing[after..]);
        }
    }
    let mut out = existing.to_string();
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
    if !out.is_empty() {
        out.push('\n');
    }
    out.push_str(&block);
    out
}

fn current_block(doc: &str) -> Option<&str> {
    let b = doc.find(BEGIN)?;
    let e = doc.find(END)? + END.len();
    (b < e).then(|| &doc[b..e])
}

fn run_example(root: &Path, mode: &str) -> Result<String, String> {
    let output = Command::new("cargo")
        .current_dir(root)
        .args([
            "run",
            "-q",
            "--release",
            "--example",
            "pq_measure",
            "--",
            mode,
        ])
        .output()
        .map_err(|e| format!("cargo could not start: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "examples/pq_measure.rs failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|e| format!("the example printed non UTF-8: {e}"))
}

fn usage() -> Report {
    Report::fail_with(
        "usage: pq-measure [--write | --check | --timings | --self-test]\n".to_string(),
        2,
    )
}

/// The canary: the splice must replace its own block, keep the rest of the
/// document, and an out of date block must differ from a fresh one.
///
/// # Errors
///
/// When the splice loses text or fails to replace the block.
pub fn self_test() -> Result<String, String> {
    let doc = "# Title\n\ntext before\n";
    let first = splice(doc, "one\n");
    let second = splice(&first, "two\n");
    if !second.contains("two\n") || second.contains("one\n") {
        return Err("a second splice did not replace the first block".to_string());
    }
    if !second.starts_with("# Title\n\ntext before\n") {
        return Err("the splice changed the text before the block".to_string());
    }
    if second.matches(BEGIN).count() != 1 {
        return Err("the splice duplicated the block".to_string());
    }
    if current_block(&first) == current_block(&second) {
        return Err("a stale block compared equal to a fresh one".to_string());
    }
    Ok("pq-measure self-test ok".to_string())
}

/// Run the tool with its command line arguments.
#[must_use]
pub fn cli(args: &[&str], root: &Path) -> Report {
    let mode = match args {
        [] => "print",
        ["--write"] => "write",
        ["--check"] => "check",
        ["--timings"] => "timings",
        ["--self-test"] => "self-test",
        _ => return usage(),
    };
    if mode == "self-test" {
        return match self_test() {
            Ok(msg) => Report::ok(format!("{msg}\n")),
            Err(e) => Report::fail_with(format!("{e}\n"), 1),
        };
    }
    let example_mode = if mode == "timings" {
        "timings"
    } else {
        "tables"
    };
    let section = match run_example(root, example_mode) {
        Ok(s) => s,
        Err(e) => return Report::fail_with(format!("{e}\n"), 1),
    };
    let doc_path = root.join(DOC_REL);
    match mode {
        "write" => {
            let existing = std::fs::read_to_string(&doc_path).unwrap_or_default();
            match std::fs::write(&doc_path, splice(&existing, &section)) {
                Ok(()) => Report::ok(format!("wrote the pq-measure section of {DOC_REL}\n")),
                Err(e) => Report::fail_with(format!("{DOC_REL} could not be written: {e}\n"), 1),
            }
        }
        "check" => {
            let Ok(doc) = std::fs::read_to_string(&doc_path) else {
                return Report::fail_with(format!("missing {DOC_REL}\n"), 1);
            };
            if current_block(&doc) == Some(wrap(&section).trim_end_matches('\n')) {
                Report::ok("pq-measure section is current\n".to_string())
            } else {
                Report::fail_with(
                    format!(
                        "the pq-measure section of {DOC_REL} does not match the node library; \
run `cargo run --manifest-path xtask/tools/Cargo.toml -- pq-measure --write`\n"
                    ),
                    1,
                )
            }
        }
        _ => Report::ok(section),
    }
}
